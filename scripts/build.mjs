import { prepareStaticWorkers } from './vendor-static.mjs';
import { build } from 'esbuild';
import { mkdir, cp, readFile, rm, stat } from 'node:fs/promises';
import { createReadStream } from 'node:fs';
import { createHash } from 'node:crypto';
const model = JSON.parse(await readFile('models/model.json','utf8'));
const path = `models/${model.file}`;
if ((await stat(path).catch(()=>null))?.size !== model.bytes) throw new Error('公式GGUFモデルがありません。npm run model:download を実行してください。');
const hash = createHash('sha256');
for await (const chunk of createReadStream(path)) hash.update(chunk);
if (hash.digest('hex') !== model.sha256) throw new Error('モデルのSHA-256が一致しません。');
await rm('dist',{recursive:true,force:true});
await mkdir('dist/vendor',{recursive:true});
await mkdir('dist/models',{recursive:true});
await cp('LICENSE','dist/LICENSE');
await mkdir('dist/icons',{recursive:true});
for (const size of [16, 32, 48, 128]) await cp(`src/icons/icon-${size}.png`,`dist/icons/icon-${size}.png`);
for (const file of ['manifest.json','popup.html','popup.css','offscreen.html']) await cp(`src/${file}`,`dist/${file}`);
for (const file of [model.file,'model.json','LICENSE.en','LICENSE.ja']) await cp(`models/${file}`,`dist/models/${file}`);
await cp('node_modules/@wllama/wllama/esm/wasm/wllama.wasm','dist/vendor/wllama.wasm');
await cp('node_modules/@wllama/wllama/LICENSE','dist/vendor/wllama-LICENSE').catch(async()=>cp('node_modules/@wllama/wllama/LICENCE','dist/vendor/wllama-LICENSE'));
const staticVendor = await prepareStaticWorkers();
await build({plugins:[{name:'mv3-static-workers',setup(b){b.onLoad({filter:/wllama\/esm\/index\.js$/},()=>({contents:staticVendor,loader:'js'}));}}],entryPoints:['src/background.js','src/offscreen.js','src/popup.js'],outdir:'dist',bundle:true,format:'esm',target:'chrome137',legalComments:'eof'});
await build({entryPoints:['src/content.js'],outdir:'dist',bundle:true,format:'iife',target:'chrome137'});
console.log(`Built dist/ with verified ${model.file} (${model.bytes} bytes).`);
